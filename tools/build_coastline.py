"""Convert a Natural Earth coastline GeoJSON into a compact TypeScript module.

Usage:
    python3 -I tools/build_coastline.py <ne_110m_coastline.geojson> data/coastline110m.ts

Natural Earth data is in the public domain (https://www.naturalearthdata.com/about/terms-of-use/).
Coordinates are rounded to 0.1 degree (about 11 km), far below what a 30 cm globe can show,
and consecutive duplicate points created by rounding are removed.
"""

import json
import sys


def to_lines(geometry):
    t = geometry.get("type")
    if t == "LineString":
        return [geometry["coordinates"]]
    if t == "MultiLineString":
        return list(geometry["coordinates"])
    raise ValueError("unexpected geometry type: %r" % t)


def main(src, dst):
    with open(src, "r", encoding="utf-8") as fh:
        data = json.load(fh)
    if data.get("type") != "FeatureCollection":
        raise ValueError("not a FeatureCollection")

    polylines = []
    points_in = 0
    for feature in data["features"]:
        for line in to_lines(feature["geometry"]):
            points_in += len(line)
            flat = []
            last = None
            for lon, lat in ((p[0], p[1]) for p in line):
                if not (-180.0 <= lon <= 180.0 and -90.0 <= lat <= 90.0):
                    raise ValueError("coordinate out of range: %r, %r" % (lon, lat))
                q = (round(lon, 1), round(lat, 1))
                if q != last:
                    flat.extend(q)
                    last = q
            if len(flat) >= 4:
                polylines.append(flat)

    points_out = sum(len(p) // 2 for p in polylines)

    def num(v):
        s = ("%.1f" % v).rstrip("0").rstrip(".")
        return "0" if s in ("-0", "") else s

    body = ",\n".join("  [" + ",".join(num(v) for v in p) + "]" for p in polylines)
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/build_coastline.py from Natural Earth 1:110m coastlines.\n")
        fh.write("// Public domain data: https://www.naturalearthdata.com/about/terms-of-use/\n")
        fh.write("// %d polylines, %d points (from %d source points). Do not edit by hand.\n"
                 % (len(polylines), points_out, points_in))
        fh.write("// Each polyline is a flat array [lon0, lat0, lon1, lat1, ...] in degrees.\n\n")
        fh.write("export const COASTLINE_110M: number[][] = [\n")
        fh.write(body)
        fh.write("\n];\n")
    print("polylines=%d points_in=%d points_out=%d" % (len(polylines), points_in, points_out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
